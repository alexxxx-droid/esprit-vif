// La grammaire des formes : genre et pluriel des noms (« cerchio » → « i cerchi », « croce » → « le croci »).

/** Les formes au nom féminin : la stella, la croce, la luna, la bandiera. */
const FEMININE: ReadonlySet<ShapeKind> = new Set(['star', 'cross', 'moon', 'flag']);

/** Début de mot qui demande « lo » / « gli » au masculin (lo specchio, gli zaini, gli gnomi). */
const IMPURE = /^(s[^aeiouàèéìòù]|z|gn|ps|pn|x|y|i[aeiou])/i;
const VOWEL_START = /^[aeiouàèéìòù]/i;

/** Le pluriel d'un nom italien : -io → -i, -co → -chi, -o / -e → -i, -ca → -che, -cia → -ce, -a → -e (féminin). */
function pluralOf(name: string, feminine: boolean): string {
  if (/io$/.test(name)) return name.slice(0, -1);
  if (/[cg]o$/.test(name)) return `${name.slice(0, -1)}hi`;
  if (/[oe]$/.test(name)) return `${name.slice(0, -1)}i`;
  if (/[cg]a$/.test(name)) return `${name.slice(0, -1)}he`;
  if (/[aeiou][cg]ia$/.test(name)) return `${name.slice(0, -1)}e`;
  if (/[cg]ia$/.test(name)) return `${name.slice(0, -2)}e`;
  if (/a$/.test(name)) return feminine ? `${name.slice(0, -1)}e` : `${name.slice(0, -1)}i`;
  // Mots terminés par une voyelle accentuée ou une consonne : invariables.
  return name;
}

/** L'article défini singulier : il cerchio, lo zaino, l’esagono, la stella, l’ancora (mais lo iato, la iena). */
function theArticle(name: string, feminine: boolean): string {
  if (/^i[aeiou]/i.test(name)) return feminine ? 'la ' : 'lo ';
  if (VOWEL_START.test(name)) return 'l’';
  if (feminine) return 'la ';
  return IMPURE.test(name) ? 'lo ' : 'il ';
}

/** L'article défini pluriel : i cerchi, gli esagoni, gli zaini, le stelle. */
function pluralArticle(plural: string, feminine: boolean): string {
  if (feminine) return 'le';
  return VOWEL_START.test(plural) || IMPURE.test(plural) ? 'gli' : 'i';
}

/** « pieno » ou « vuoto », accordé : pieno, piena, pieni, piene. */
function fill(shape: ShapeKind, filled: boolean, plural: boolean): string {
  const ending = FEMININE.has(shape) ? (plural ? 'e' : 'a') : plural ? 'i' : 'o';
  return `${filled ? 'pien' : 'vuot'}${ending}`;
}

/** Une énumération : « a », « a e b », « a, b e c » (« ed » devant un mot qui commence par e). */
function list(items: readonly string[]): string {
  if (items.length < 2) return items[0] ?? '';
  const last = items[items.length - 1];
  const and = /^[eè]/i.test(last) ? 'ed' : 'e';
  return `${items.slice(0, -1).join(', ')} ${and} ${last}`;
}

const grammar: LangGrammar = {
  fillWord: (shape, filled, plural) => fill(shape, filled, plural),
  theShape: (shape, name) => `${theArticle(name, FEMININE.has(shape))}${name}`,
  describeShape: (card, name) => {
    const base = `${name} ${fill(card.shape, card.filled, false)}`;
    if (!card.rotation) return base;
    return `${base}, ruotat${FEMININE.has(card.shape) ? 'a' : 'o'} di ${card.rotation}°`;
  },
  countShapes: (shape, name, count) => `${count} ${pluralOf(name, FEMININE.has(shape))}`,
  describeRule: (parts, inverted) => {
    const items = parts.map(({ shape, name, fill: wanted }) => {
      const feminine = FEMININE.has(shape);
      const plural = pluralOf(name, feminine);
      const adjective = wanted ? ` ${fill(shape, wanted === 'filled', true)}` : '';
      return `${pluralArticle(plural, feminine)} ${plural}${adjective}`;
    });
    return inverted ? `Tocca tutto tranne ${list(items)}` : `Tocca ${list(items)}`;
  },
  list,
};

